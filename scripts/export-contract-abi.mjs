import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const abi = JSON.parse(execFileSync("forge", ["inspect", "--root", "contracts", "PayrSettlement", "abi", "--json"], { encoding: "utf8" }));
const payment = abi.find((entry) => entry.type === "function" && entry.name === "payInvoice");
const event = abi.find((entry) => entry.type === "event" && entry.name === "InvoicePaid");
if (payment?.stateMutability !== "payable" || payment.inputs.map((input) => input.type).join(",") !== "bytes32,bytes32,address,uint256,uint64,uint64,bytes"
  || event?.inputs.map((input) => `${input.type}:${input.indexed}`).join(",") !== "bytes32:true,bytes32:false,address:true,address:true,uint256:false") throw new Error("Unexpected settlement ABI");
const source = `// Generated by scripts/export-contract-abi.mjs. Do not edit manually.\nexport const payrSettlementAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
const path = "src/lib/chain/abi.ts";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== source) throw new Error("Settlement ABI is stale");
} else writeFileSync(path, source);
